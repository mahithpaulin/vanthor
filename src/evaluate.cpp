    void load_piece(Piece p, const int mg[8][8], const int eg[8][8]) {
        for (int row = 0; row < 8; row++) {
            int rank = 7 - row;
            for (int f = 0; f < 8; f++) {
                MG[p][make_sq(f, rank)] = mg[row][f];
                EG[p][make_sq(f, rank)] = eg[row][f];
            }
        }
    }

    bool LOADED = false;
    void ensure_loaded() {
        if (LOADED) return;
        load_piece(PAWN, ROW_P_MG, ROW_P_EG);
        load_piece(KNIGHT, ROW_N_MG, ROW_N_EG);
        load_piece(BISHOP, ROW_B_MG, ROW_B_EG);
        load_piece(ROOK, ROW_R_MG, ROW_R_MG);
        load_piece(QUEEN, ROW_Q_MG, ROW_Q_EG);
        load_piece(KING, ROW_K_MG, ROW_K_EG);
        LOADED = true;
    }
